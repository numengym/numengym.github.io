// The enchants an item can take: [{ id, name }], by name. item: a db.js item ({ t: type, ht: hand type, wt: weapon
// type }). A two-hander takes two-hand and any-weapon enchants; a shield (weapon type 7) only shield ones; a
// held-in-off-hand item (5) only off-hand ones. Scopes go on a hunter's bow, gun or crossbow (scopes: false
// for other classes, whose ranged slot is a wand, a thrown weapon or a relic).
export function enchantsFor(item, { scopes = true } = {}) {
  if (!item) return [];
  const out = [];
  for (const [id, entries] of Object.entries(ENCHANT_SLOTS)) {
    for (const [types, kind, name] of entries) {
      if (!types.includes(item.t)) continue;
      if (item.t === 14 && !scopes) continue;
      if (item.t === 13) {
        const shield = item.wt === 7;
        const held = item.wt === 5;
        if (kind === 1 && item.ht !== 4) continue;
        if (kind === 2 && !shield) continue;
        if (kind === 5 && !held) continue;
        if (kind === 0 && (shield || held)) continue;
      }
      out.push({ id: Number(id), name });
      break;
    }
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}
